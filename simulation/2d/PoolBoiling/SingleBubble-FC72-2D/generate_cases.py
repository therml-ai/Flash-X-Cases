"""Generates the case-twall-<T> subdirectories of SingleBubble-FC72-2D.

Every case-twall-* directory, and every file in it, is written by this script.
Do not edit them by hand: change flash.toml here (the base shared by every
case) or the FC72 table below, then regenerate with --force.

    python generate_cases.py --wall_temp 80 90 100
    python generate_cases.py --wall_temp 100 --set Driver.tmax=100 --force
    jobrunner setup simulation/2d/PoolBoiling/SingleBubble-FC72-2D
    jobrunner submit simulation/2d/PoolBoiling/SingleBubble-FC72-2D/case-twall-100
    python generate_cases.py --clean      # remove every generated case directory

For each physical heater temperature T (in C) the script writes case-twall-T/
    flash.toml       only what differs from the base, in [Override.<Unit>]
                     tables, plus a [Physical] table that Flash-X never sees
                     but which records how to re-dimensionalize the output.
                     At submit, flashInput.py merges it with the base,
                     applies the overrides and writes flash.par. jobrunner
                     only writes job.input at setup, so cases don't use it.
    parameters.json  the effective parameters of the case (base with the
                     overrides applied) and the Physical table in one record
    Jobfile          so jobrunner treats the directory as a runnable case

Flash-X is built once from the base flash.toml (jobrunner setup on this
directory). mph_Stefan and the Simulation scales are runtime parameters, so
every case runs the same executable.

Re-dimensionalization, with the Physical values of a case:

    x     = length_scale   * x*                 [m]
    t     = time_scale     * t*                 [s]
    u     = velocity_scale * u*                 [m/s]
    T     = bulk_temp + temp_scale * T*         [C]
    q''   = heat_flux_scale * Nu*               [W/m^2]

where Nu* = -dT*/dn* is the nondimensional temperature gradient into the
fluid at the wall, and heat_flux_scale = thco_liquid * temp_scale /
length_scale. In vapor, multiply by mph_thcoGas (k_vapor / k_liquid).

The fluid is saturated FC-72 at 1 atm. The base flash.toml carries the
dimensionless groups of the BubbleML PoolBoiling-Saturated-FC72-2D dataset;
only mph_Stefan depends on the wall temperature.
"""

import argparse
import glob
import json
import math
import os
import shutil

import toml

TEMPLATE_DIR = os.path.dirname(os.path.abspath(__file__))

# Saturated FC-72 at 1 atm
FC72 = {
    "sat_temp": 58.0,                      # C
    "stefan_coefficient": 0.013,           # 1/K, Cp_liquid / h_fg
    "length_scale": 7.0e-4,                # m, capillary length sqrt(sigma / (g (rho_l - rho_v)))
    "gravity": 9.81,                       # m/s^2
    "rho_liquid": 1620.0,                  # kg/m^3
    "thco_liquid": 0.054,                  # W/(m K)
}

GENERATED_MARK = "# GENERATED by SingleBubble-FC72-2D/generate_cases.py."

CASE_JOBFILE = f"""\
# YAML configuration file for `jobrunner`.
{GENERATED_MARK} Do not edit; regenerate.
job:
  input:
    - flash.toml
  archive:
    - flash.par
    - parameters.json
    - "INS*"
    - "*_hdf5_*"
    - "*.log"
    - "*.out"
  clean:
    - flash.par
    - "INS*"
    - "*_hdf5_*"
    - "*.log"
    - "unitTest*"
    - "*.out"
"""


def physical_parameters(wall_temp, fluid=FC72):
    """Scales that turn the nondimensional output of a case into SI units.

    Temperatures are nondimensionalized as T* = (T - T_bulk) / (T_wall - T_bulk).
    The bulk liquid is saturated, so T_bulk = T_sat, mph_Tsat = 0, and
    temp_scale is the wall superheat.
    """
    temp_scale = wall_temp - fluid["sat_temp"]
    if temp_scale <= 0.0:
        raise SystemExit(f"wall temperature {wall_temp:g} C is not above T_sat = {fluid['sat_temp']:g} C")
    velocity_scale = math.sqrt(fluid["gravity"] * fluid["length_scale"])
    return {
        "fluid": "FC-72",
        "sat_temp": fluid["sat_temp"],
        "bulk_temp": fluid["sat_temp"],
        "wall_temp": wall_temp,
        "temp_scale": temp_scale,
        "length_scale": fluid["length_scale"],
        "velocity_scale": velocity_scale,
        "time_scale": fluid["length_scale"] / velocity_scale,
        "gravity": fluid["gravity"],
        "rho_liquid": fluid["rho_liquid"],
        "thco_liquid": fluid["thco_liquid"],
        "heat_flux_scale": fluid["thco_liquid"] * temp_scale / fluid["length_scale"],
    }


def case_overrides(physical, fluid=FC72):
    """Flash-X runtime parameters a case changes from the base, by unit."""
    return {
        "Multiphase": {
            # Cp_l (T_wall - T_bulk) / h_fg
            "mph_Stefan": fluid["stefan_coefficient"] * physical["temp_scale"],
        },
        "Simulation": {
            "sim_lengthScaleMeters": physical["length_scale"],
            "sim_timeScaleSeconds": physical["time_scale"],
            "sim_tempScaleExpr": f"{physical['temp_scale']:.6g}*T + {physical['bulk_temp']:.6g}",
        },
    }


def parse_value(text):
    """bool, int, float, or string, so `100` is written unquoted and `noslip_ins` quoted."""
    if text.lower() in ("true", "false"):
        return text.lower() == "true"
    for cast in (int, float):
        try:
            return cast(text)
        except ValueError:
            pass
    return text


def parse_set(items, base):
    """--set Unit.key=value, checked against the base so a typo fails here."""
    overrides = {}
    for item in items:
        name, separator, value = item.partition("=")
        group, dot, key = name.partition(".")
        if not separator or not dot:
            raise SystemExit(f"--set expects Unit.key=value, got {item!r}")
        if key not in base.get(group, {}):
            raise SystemExit(f"--set {name}: not in the base flash.toml; add it there so setup checks it")
        overrides.setdefault(group, {})[key] = parse_value(value)
    return overrides


def format_value(value):
    if isinstance(value, bool):
        return str(value).lower()
    return f'"{value}"' if isinstance(value, str) else repr(value)


def render_table(name, values):
    return f"[{name}]\n" + "".join(f"  {key} = {format_value(value)}\n" for key, value in values.items())


def render_case_toml(wall_temp, overrides, physical):
    """The case's flash.toml. Only [Override.<Unit>] and [Physical] appear
    here; flashInput.py merges it with the base at submit."""
    tables = [render_table(f"Override.{group}", values) for group, values in overrides.items()]
    tables.append(render_table("Physical", physical))
    return (f"{GENERATED_MARK} Do not edit;\n"
            "# change the base flash.toml or the FC72 table there and regenerate.\n"
            "# flashInput.py merges this with ../flash.toml at submit.\n"
            f"# FC-72 with the heater at {wall_temp:g} C\n\n"
            + "\n".join(tables))


def effective_parameters(base, overrides, physical):
    """Base with the overrides applied, as flashInput.py builds flash.par."""
    params = json.loads(json.dumps(base))
    for group, values in overrides.items():
        params[group].update(values)
    params["Physical"] = physical
    return params


def write_case(directory, base, wall_temp, extra, force):
    physical = physical_parameters(wall_temp)
    overrides = case_overrides(physical)
    for group, values in extra.items():
        overrides.setdefault(group, {}).update(values)

    if os.path.exists(directory):
        if not is_generated(directory):
            raise SystemExit(f"not generated by this script, refusing to touch: {directory}")
        if not force:
            print(f"exists, skipping (use --force to overwrite): {directory}")
            return
        shutil.rmtree(directory)
    os.makedirs(directory)

    with open(os.path.join(directory, "flash.toml"), "w") as toml_file:
        toml_file.write(render_case_toml(wall_temp, overrides, physical))
    with open(os.path.join(directory, "parameters.json"), "w") as json_file:
        json.dump(effective_parameters(base, overrides, physical), json_file, indent=4)
    with open(os.path.join(directory, "Jobfile"), "w") as jobfile:
        jobfile.write(CASE_JOBFILE)
    print(f"wrote {directory}")


def is_generated(directory):
    """Only directories this script wrote carry the mark in their Jobfile, so a
    hand-made directory with a matching name is never removed."""
    try:
        with open(os.path.join(directory, "Jobfile")) as jobfile:
            return GENERATED_MARK in jobfile.read()
    except OSError:
        return False


def clean_cases():
    for directory in sorted(glob.glob(os.path.join(TEMPLATE_DIR, "case-twall-*"))):
        if is_generated(directory):
            shutil.rmtree(directory)
            print(f"removed {directory}")
        else:
            print(f"not generated by this script, left alone: {directory}")


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--wall_temp", nargs="+", type=float, metavar="C",
                        help="physical heater temperatures in C, one case each")
    parser.add_argument("--set", action="append", metavar="Unit.key=value", default=[],
                        help="extra override applied to every case, e.g. Driver.tmax=100")
    parser.add_argument("--force", action="store_true", help="overwrite existing case directories")
    parser.add_argument("--clean", action="store_true", help="remove every generated case directory")
    args = parser.parse_args()

    if args.clean:
        clean_cases()
    if not args.wall_temp:
        if not args.clean:
            parser.error("give --wall_temp or --clean")
        return

    base = toml.load(os.path.join(TEMPLATE_DIR, "flash.toml"))
    for table in ("Override", "Physical"):
        if table in base:
            raise SystemExit(f"[{table}] belongs in the generated case files, not the base flash.toml")
    extra = parse_set(args.set, base)

    for wall_temp in args.wall_temp:
        write_case(os.path.join(TEMPLATE_DIR, f"case-twall-{wall_temp:g}"), base, wall_temp, extra, args.force)


if __name__ == "__main__":
    main()
